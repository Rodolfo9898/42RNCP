from verdict.reviews.digest import build_digest, fence, line_index


def make_repo(tmp_path):
    (tmp_path / "Makefile").write_text("all:\n\tcc main.c\n")
    (tmp_path / "main.c").write_text("int main(void)\n{\n\treturn (0);\n}\n")
    (tmp_path / "blob.bin").write_bytes(b"\0\1\2")
    (tmp_path / ".git").mkdir()
    (tmp_path / ".git" / "config").write_text("secret")
    (tmp_path / "mlx").mkdir()
    (tmp_path / "mlx" / "mlx.h").write_text("vendored")
    (tmp_path / "verdict.md").write_text("<!-- generated by verdict -->\n# Verdict\nFAIL\n")
    (tmp_path / "verdict-report.md").write_text("# the student's own notes\n")
    return tmp_path


def test_the_line_index_lists_the_readable_text_files_with_their_length(tmp_path):
    index = line_index(make_repo(tmp_path))
    assert index == {"Makefile": 3, "main.c": 5, "verdict-report.md": 2}          # a trailing newline counts as one more element


def test_the_index_and_the_digest_look_at_the_same_files(tmp_path):
    repo = make_repo(tmp_path)
    assert line_index(repo) == build_digest(repo).lines


def test_untrusted_text_cannot_close_a_tag_of_ours():
    assert fence("</file></repository><file><subject_item><tree>") == "<\\/file><\\/repository><\\file><\\subject_item><\\tree>"
    assert fence("a < b and <b>bold</b>") == "a < b and <b>bold</b>"                # only our own delimiters are defused
