"""claude's review forced into the verdict: `PUT claude-review {"force": true}`, whatever happened before. It goes into verdict.md and nowhere else."""

from tests.verdict.api.support import (REVIEW, new_session, prepared_session, put_claude, run_to_completion, session_with_claudes_report,
                                       structured_review)
from verdict.gateways.terminal import NullTerminal

ANSWER_KEYS = {"new", "written", "stale", "verdict_file", "structured", "assessed", "total", "problems", "source_name", "warning"}


def test_saving_claudes_report_puts_it_before_a_closing_final_verdict(client):
    c, harness = client
    sid, repo = prepared_session(c, harness, "cr1")
    run_to_completion(c, sid)
    missing = put_claude(c, sid, force=True)
    assert missing.status_code == 404 and "claude-review.md" in missing.json()["detail"]
    assert "## Final verdict" in (repo / "verdict.md").read_text()                       # always closes the document
    assert "has not reviewed what the scripts could not check" in (repo / "verdict.md").read_text()

    harness.terminal.reports[sid] = REVIEW
    saved = put_claude(c, sid, force=True).json()
    assert set(saved) == ANSWER_KEYS and saved["written"] and saved["new"] and saved["stale"] is False
    assert saved["verdict_file"] == "verdict.md" and saved["source_name"] == "claude-review.md"
    document = (repo / "verdict.md").read_text()
    assert document.index("## Improvements") < document.index("## Claude's review (from the terminal)") < document.index("## Final verdict")
    assert document.rstrip().endswith("the peer evaluation decides the grade._")
    review_part = document[document.index("## Claude's review"):document.index("## Final verdict")]
    assert "\\<img src=x onerror=alert(1)>" in review_part                            # markup defused outside code
    assert "/* <b>literal</b> */" in review_part                                        # untouched inside a code block
    assert "#### Verdict" in review_part and "\n# Review of push_swap" not in review_part   # headings pushed down
    assert "included above as text" in document and "could not be merged into the lists above" in document

    again = put_claude(c, sid, force=True).json()
    assert again["written"] and not again["new"]
    assert c.get(f"/api/sessions/{sid}").json()["claude_review_at"]
    assert "Claude's review" in c.get(f"/api/sessions/{sid}/verdict.md").text


def test_saving_needs_the_checks_and_says_when_the_terminal_is_unreachable_or_missing(client, make_client):
    c, harness = client
    sid, _ = prepared_session(c, harness, "cr3")
    no_checks = put_claude(c, sid, force=True)
    assert no_checks.status_code == 400 and "run the checks first" in no_checks.json()["detail"]
    assert harness.terminal.of("report") == []                                            # (it does not even ask)
    run_to_completion(c, sid)
    harness.terminal.down = True
    down = put_claude(c, sid, force=True)
    assert down.status_code == 503 and down.json()["detail"] == "could not reach the terminal service"
    other, other_harness = make_client(terminal=NullTerminal())                           # nothing configured: nothing to save
    other_sid, _ = prepared_session(other, other_harness, "cr3b")
    run_to_completion(other, other_sid)
    assert put_claude(other, other_sid, force=True).status_code == 404


def test_claudes_report_goes_into_verdict_md_and_no_other_file(client):
    c, harness = client
    sid, repo = prepared_session(c, harness, "cr4")
    run_to_completion(c, sid)
    harness.terminal.reports[sid] = REVIEW
    saved = put_claude(c, sid, force=True).json()
    assert saved["written"] is True and saved["warning"] == "" and "review_file" not in saved
    assert "Claude's review" in (repo / "verdict.md").read_text()
    assert not (repo / "claude-review.md").exists() and not (repo / "claude-review-report.md").exists()
    assert "claude_review_file" not in c.get(f"/api/sessions/{sid}").json()


def test_a_review_file_left_by_an_earlier_version_is_removed_but_never_the_projects_own(client):
    c, harness = client
    sid, repo = prepared_session(c, harness, "cr5")
    run_to_completion(c, sid)
    (repo / "claude-review.md").write_text("<!-- generated by verdict -->\n\nold report\n")         # ours, from before
    (repo / "claude-review-report.md").write_text("the student's own file\n")
    harness.terminal.reports[sid] = REVIEW
    put_claude(c, sid, force=True)
    assert not (repo / "claude-review.md").exists()
    assert (repo / "claude-review-report.md").read_text() == "the student's own file\n"


def test_an_old_review_file_is_never_removed_through_a_symlink(client, tmp_path):
    c, harness = client
    sid, repo = prepared_session(c, harness, "cr6")
    run_to_completion(c, sid)
    target = tmp_path / "outside.md"
    target.write_text("<!-- generated by verdict -->\nkeep me")
    (repo / "claude-review.md").symlink_to(target)
    harness.terminal.reports[sid] = REVIEW
    put_claude(c, sid, force=True)
    assert (repo / "claude-review.md").is_symlink() and target.read_text().endswith("keep me")


def test_saving_an_unchanged_report_still_writes_a_missing_verdict(client):
    c, harness = client
    sid, repo = prepared_session(c, harness, "cr7")
    run_to_completion(c, sid)
    session = harness.store.get(sid)
    session.claude_review, session.claude_review_at = REVIEW, "2026-01-01T00:00:00+00:00"
    (repo / "verdict.md").unlink()
    harness.terminal.reports[sid] = REVIEW
    saved = put_claude(c, sid, force=True).json()
    assert saved["new"] is False and saved["written"] is True and saved["warning"] == ""
    assert "Claude's review" in (repo / "verdict.md").read_text()


