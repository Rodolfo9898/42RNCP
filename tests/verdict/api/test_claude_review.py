def test_saving_forces_claudes_review_into_verdict_md_in_the_project(client):
    c, harness = client
    sid, repo, _ = session_with_claudes_report(c, harness, "ap2")
    assert "note for 1" not in (repo / "verdict.md").read_text()                        # the run wrote a verdict without the review
    body = put_claude(c, sid, force=True).json()
    assert body["written"] is True and body["structured"] is True and body["assessed"] == body["total"] > 0 and body["problems"] == []
