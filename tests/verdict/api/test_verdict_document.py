"""verdict.md in the reviewed project: written by a run, never over a file that is not ours, and the same as the verdict the app shows."""

from tests.verdict.api.support import REVIEW, made_session, prepared_session, run_to_completion
from verdict.core.models import CheckResult
from verdict.documents.verdict_file import VerdictFile

MARKER = "<!-- generated by verdict -->"


def test_verdict_is_written_into_the_repository_with_improvements(client):
    c, harness = client
    sid, repo = prepared_session(c, harness)
    state = run_to_completion(c, sid)
    assert state["verdict_file"] == "verdict.md"
    written = (repo / "verdict.md").read_text()
    assert written.startswith(MARKER) and "## Improvements" in written
    assert "no README found" in written
    assert any(i["title"] == "No README found" for i in state["improvements"])
    assert state["readme"]["present"] is False
    again = run_to_completion(c, sid)                                       # running again must not treat our own verdict as part of the project
    assert not any("verdict.md" in e["file"] for r in again["results"] for e in r["evidence"])


def test_a_projects_own_verdict_md_is_never_overwritten(client):
    c, harness = client
    sid, repo = prepared_session(c, harness, "own")
    (repo / "verdict.md").write_text("# my own notes\n")
    state = run_to_completion(c, sid)
    assert (repo / "verdict.md").read_text() == "# my own notes\n"
    assert state["verdict_file"] == "verdict-report.md"
    assert (repo / "verdict-report.md").read_text().startswith(MARKER)
    again = run_to_completion(c, sid)                                       # (the second name is ours now: it is refreshed, not skipped)
    assert again["verdict_file"] == "verdict-report.md" and (repo / "verdict.md").read_text() == "# my own notes\n"


def test_verdict_is_never_written_through_a_symlink(client, tmp_path):
    c, harness = client
    sid, repo = prepared_session(c, harness, "link")
    target = tmp_path / "outside.txt"
    target.write_text("keep me")
    (repo / "verdict.md").symlink_to(target)
    (repo / "verdict-report.md").symlink_to(target)
    state = run_to_completion(c, sid)
    assert target.read_text() == "keep me"
    assert state["verdict_file"] == "" and "Could not save the verdict" in state["message"]


def test_verdict_md_in_the_clone_follows_the_verdict_shown_in_the_app(client):
    c, harness = client
    sid, session = made_session(c, harness, name="proj")
    (harness.settings.projects / "proj").mkdir()
    harness.document.write(session)
    file = harness.settings.projects / "proj" / "verdict.md"
    assert "**PASS**" in file.read_text()
    # the verdict changes after the file was written (something now needs a second look)
    session.results.append(CheckResult(rule_id="r2", title="Check by hand", status="manual", section="mandatory"))
    assert c.get(f"/api/sessions/{sid}").json()["summary"]["overall"] == "PASS WITH ISSUES"
    assert "PASS WITH ISSUES" in file.read_text()
    before = file.read_text()                                               # unchanged: not rewritten again (only the generated time could differ)
    stamp = file.stat().st_mtime_ns
    c.get(f"/api/sessions/{sid}")
    assert file.read_text() == before and file.stat().st_mtime_ns == stamp
    file.write_text("# my own notes\n")                                     # a verdict.md that is the project's own is never touched
    c.get(f"/api/sessions/{sid}")
    assert file.read_text() == "# my own notes\n"


def test_opening_the_session_heals_a_missing_verdict_and_clears_an_old_review_file(client):
    c, harness = client
    sid, repo = prepared_session(c, harness, "cr8")
    run_to_completion(c, sid)
    session = harness.store.get(sid)
    session.claude_review, session.review_context = REVIEW, harness.context.of(session)           # (a review made for this very context)
    (repo / "verdict.md").unlink()
    (repo / "claude-review.md").write_text(MARKER + "\n\nold report\n")
    c.get(f"/api/sessions/{sid}")
    assert (repo / "verdict.md").exists() and not (repo / "claude-review.md").exists()
    assert "Claude's review" in (repo / "verdict.md").read_text()


def test_the_verdict_is_not_touched_while_a_run_or_an_ai_review_is_in_progress(client):
    c, harness = client
    sid, repo = prepared_session(c, harness, "busy")
    run_to_completion(c, sid)
    session = harness.store.get(sid)
    (repo / "verdict.md").unlink()
    session.state = "running"
    assert harness.document.ensure_current(session) is False and not (repo / "verdict.md").exists()
    session.state, session.ai.state = "done", "running"
    assert harness.document.ensure_current(session) is False and not (repo / "verdict.md").exists()
    session.ai.state = "idle"
    assert harness.document.ensure_current(session) is True and (repo / "verdict.md").is_file()


def test_nothing_is_written_for_a_session_without_a_project_folder_or_without_results(client):
    c, harness = client
    sid, session = made_session(c, harness, name="gone")                     # the folder of the project does not exist
    harness.document.write(session)
    assert session.verdict_file == "" and "Could not save the verdict" in session.message
    session.repo, session.message = None, ""
    harness.document.write(session)
    assert session.verdict_file == "" and session.message == "" and "# Verdict" in harness.document.text(session)
    session.results = []
    assert harness.document.ensure_current(session) is False


def test_removing_the_verdict_deletes_only_what_this_app_wrote(client, tmp_path):
    c, harness = client
    sid, session = made_session(c, harness, name="rm")
    root = harness.settings.projects / "rm"
    root.mkdir()
    harness.document.write(session)
    (root / "verdict-report.md").write_text("student's own\n")
    outside = tmp_path / "outside.md"
    outside.write_text(MARKER + "\nelsewhere\n")
    (root / "claude-review.md").symlink_to(outside)
    harness.document.remove(session)
    assert [p.name for p in sorted(root.iterdir())] == ["claude-review.md", "verdict-report.md"] and outside.exists()
    assert session.verdict_file == ""


def test_what_is_ours_is_a_regular_file_that_starts_with_the_marker(tmp_path):
    ours, theirs, link = tmp_path / "ours.md", tmp_path / "theirs.md", tmp_path / "link.md"
    ours.write_text(MARKER + "\nreport\n")
    theirs.write_text("# my notes\n" + MARKER)
    link.symlink_to(ours)
    assert VerdictFile.is_generated(ours) and not VerdictFile.is_generated(theirs) and not VerdictFile.is_generated(link)
    assert not VerdictFile.is_generated(tmp_path / "missing.md") and not VerdictFile.is_generated(tmp_path)
