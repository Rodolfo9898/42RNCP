def test_document_structure_and_readme_callout():
    results = [result("fail", title="Makefile rules", detail="missing re", sources=[Source(pdf="p.pdf", page=3)],
                      evidence=[Evidence(file="Makefile", line=2, snippet="all:")]),
               result("manual", title="Needs manual review", detail="Something to read.", sources=[Source(pdf="p.pdf", page=4)]),
               result("pass", title="Required files", detail="all there")]
    improvements = [
        Improvement(category="structure", priority="high", title="No README found", detail="Add one."),
        Improvement(category="logic", priority="medium", title="Possible unchecked allocation", evidence=[Evidence(file="a.c", line=5, snippet="p = malloc(1);")]),
        Improvement(category="readability", priority="low", title="Deeply nested code", source="ai"),
    ]
    md = render_markdown(repo={"url": "git@x:a/b.git", "commit": "abc", "subject": "s", "author": "me"}, subjects=["p.pdf"],
                         results=results, improvements=improvements, readme={"present": False, "name": None, "lines": 0})
    assert md.startswith("<!-- generated by verdict -->")
    order = [md.index(h) for h in ("## At a glance", "## ❌ Lacking", "## ⚠️ Second look", "## ✅ Ok", "## Improvements", "## Final verdict")]
    assert order == sorted(order)
    section = md[md.index("## Improvements"):]
    assert "**README:** ⚠ **no README found**" in section
    assert section.index("### Structure") < section.index("### Logic") < section.index("### Readability")
    assert "- **[high] No README found** — Add one." in section
    assert "`a.c:5` — `p = malloc(1);`" in section
    assert "_(AI)_" in section
    assert "### Code" not in section        # empty categories are omitted
    lacking = md[md.index("## ❌ Lacking"):md.index("## ⚠️ Second look")]
    assert "**Makefile rules** — missing re _(p.pdf p.3)_" in lacking and "`Makefile:2` — `all:`" in lacking


