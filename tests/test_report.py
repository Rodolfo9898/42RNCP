def test_claudes_review_is_defused_and_demoted_when_it_cannot_be_merged():
    text = "# Title\n## Part\nplain <script>x</script> text\n```\n<b>code</b>\n# not a heading\n```\n~~~\nunclosed <i>"
    md = render_markdown(repo=None, subjects=[], results=[result("pass")], claude_review=text,
                         claude=ClaudeReport(problems=["The report has no json block at the end, so it could not be merged."]))
    section = md[md.index("## Claude's review"):md.index("## Final verdict")]
    assert "### Title" in section and "#### Part" in section and "# not a heading" in section
    assert "\\<script>x\\</script>" in section and "<b>code</b>" in section
    assert section.count("```") % 2 == 0 and "~~~" in section
    assert "could not be merged into the lists above" in md and "included above as text" in md


