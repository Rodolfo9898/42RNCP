"""The check engine: runs every rule of a session against a cloned repository."""

from __future__ import annotations

import re
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..models import CheckResult, Evidence, Rule, Section
from ..repo import tracked_files
from ..sandbox import ExecResult, Sandbox, SandboxError

VERDICT_MARKER = "<!-- generated by verdict -->"
GENERATED_VERDICT_NAMES = ("verdict.md", "verdict-report.md", "claude-review.md", "claude-review-report.md")
SOURCE_EXTS = {".c", ".h", ".cpp", ".hpp", ".tpp", ".ipp", ".cc"}
EXEC_MAGIC = (b"\x7fELF", b"\xcf\xfa\xed\xfe", b"\xfe\xed\xfa\xcf")  # ELF; Mach-O (for local dev)
EXCLUDED_DIRS = re.compile(r"(^|/)(mlx|minilibx[\w.-]*|mlx_linux|mlx42|libmlx[\w.-]*|\.git)/", re.I)


@dataclass
class BuildResult:
    ok: bool
    log: str
    ran: bool = True


@dataclass
class Ctx:
    repo: Path
    rules: list[Rule]
    sandbox: Sandbox | None
    lang: str | None = None
    cache: dict[str, Any] = field(default_factory=dict)

    # ---- repo helpers
    def unit_dir(self, unit: str) -> Path:
        return (self.repo / unit).resolve()

    def files(self) -> list[Path]:
        if "files" not in self.cache:
            self.cache["files"] = [p for p in tracked_files(self.repo) if not self._is_generated_verdict(p)]
        return self.cache["files"]

    def _is_generated_verdict(self, rel: Path) -> bool:
        if len(rel.parts) != 1 or rel.name not in GENERATED_VERDICT_NAMES:
            return False
        try:
            return (self.repo / rel).open("rb").read(200).startswith(VERDICT_MARKER.encode())
        except OSError:
            return False

    def walk(self, base: Path) -> list[Path]:
        """Fresh listing of `base` (the cached `files()` goes stale once the repo is built)."""
        return tracked_files(base)

    def source_files(self, unit: str = ".", *, exclude_vendored: bool = True) -> list[Path]:
        """Source files (relative to the repo root) under `unit`."""
        prefix = "" if unit in (".", "") else unit.rstrip("/") + "/"
        out = []
        for p in self.files():
            s = p.as_posix()
            if p.suffix.lower() in SOURCE_EXTS and s.startswith(prefix):
                if exclude_vendored and EXCLUDED_DIRS.search("/" + s):
                    continue
                out.append(p)
        return out

    def read(self, rel: Path) -> str:
        try:
            return (self.repo / rel).read_bytes()[:1_000_000].decode("utf-8", errors="replace")
        except OSError:
            return ""

    def is_elf(self, path: Path) -> bool:
        try:
            with path.open("rb") as fh:
                return fh.read(4) in EXEC_MAGIC
        except OSError:
            return False

    def executables(self, unit: str) -> list[Path]:
        base = self.unit_dir(unit)
        if not base.is_dir():
            return []
        return sorted(p for p in base.iterdir() if p.is_file() and not p.is_symlink() and self.is_elf(p))

    # ---- rules helpers
    def units(self) -> list[str]:
        seen: dict[str, None] = {}
        for r in self.rules:
            if r.kind in ("build_unit", "program") or (r.kind == "required_files" and r.unit != "."):
                seen.setdefault(r.unit)
        return list(seen) or ["."]

    def programs(self, unit: str, section: Section | None = None) -> list[str]:
        return [
            r.params["program"] for r in self.rules
            if r.kind == "program" and r.unit == unit and (section is None or r.section == section)
        ]

    def has_makefile(self, unit: str) -> bool:
        return (self.unit_dir(unit) / "Makefile").is_file()

    # ---- sandbox helpers
    def run(self, argv: list[str], unit: str = ".", timeout: float = 60, stdin: str = "") -> ExecResult:
        if self.sandbox is None:
            raise SandboxError("no sandbox configured")
        return self.sandbox.exec(argv, self.unit_dir(unit), timeout=timeout, stdin=stdin)

    def build(self, unit: str, bonus: bool = False) -> BuildResult:
        key = f"build:{unit}:{bonus}"
        if key not in self.cache:
            if not self.has_makefile(unit):
                self.cache[key] = BuildResult(False, f"No Makefile in {unit}/", ran=False)
            else:
                res = self.run(["make", "bonus"] if bonus else ["make"], unit, timeout=240)
                log = res.output + ("\n[timed out]" if res.timed_out else "")
                self.cache[key] = BuildResult(res.ok, log)
        return self.cache[key]


Checker = Callable[[Ctx, Rule], Iterable[CheckResult]]
CHECKERS: dict[str, tuple[int, Checker]] = {}

PHASE_STATIC, PHASE_BUILD, PHASE_ANALYSIS, PHASE_RUNTIME, PHASE_FINAL = range(5)


def checker(kind: str, phase: int) -> Callable[[Checker], Checker]:
    def register(fn: Checker) -> Checker:
        CHECKERS[kind] = (phase, fn)
        return fn
    return register


def result(rule: Rule | None, status: str, detail: str = "", *, title: str | None = None,
           evidence: list[Evidence] | None = None, log: str = "", auto: bool = True) -> CheckResult:
    return CheckResult(
        rule_id=rule.id if rule else None,
        title=title or (rule.title if rule else "Check"),
        status=status,  # type: ignore[arg-type]
        detail=detail,
        section=rule.section if rule else "mandatory",
        sources=rule.sources if rule else [],
        evidence=evidence or [],
        log=log[-6000:],
        auto=auto,
    )


def strip_code(text: str) -> str:
    """Blank out comments and string/char literals (keeping line numbers intact)."""
    out: list[str] = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        two = text[i:i + 2]
        if two == "//":
            j = text.find("\n", i)
            j = n if j == -1 else j
            out.append(" " * (j - i))
            i = j
        elif two == "/*":
            j = text.find("*/", i + 2)
            j = n if j == -1 else j + 2
            out.append(re.sub(r"[^\n]", " ", text[i:j]))
            i = j
        elif c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            end = min(j, n)
            closed = end < n and text[end] == c
            out.append(c + re.sub(r"[^\n]", " ", text[i + 1:end]) + (c if closed else ""))
            i = end + (1 if closed else 0)
        else:
            out.append(c)
            i += 1
    return "".join(out)


def grep(ctx: Ctx, files: Iterable[Path], pattern: re.Pattern[str], *, code_only: bool = True,
         limit: int = 25) -> list[Evidence]:
    found: list[Evidence] = []
    for rel in files:
        raw = ctx.read(rel)
        text = strip_code(raw) if code_only else raw
        raw_lines = raw.splitlines()
        for number, line in enumerate(text.splitlines(), 1):
            if pattern.search(line):
                snippet = raw_lines[number - 1].strip()[:200] if number <= len(raw_lines) else ""
                found.append(Evidence(file=rel.as_posix(), line=number, snippet=snippet))
                if len(found) >= limit:
                    return found
    return found


def label(rule: Rule, text: str | None = None) -> str:
    base = text or rule.title
    return base if rule.unit == "." else f"{rule.unit}: {base}"


def _has_bonus(ctx: Ctx) -> bool:
    """Whether the repo contains bonus work (bonus files/directories or a `bonus` Makefile rule)."""
    if any("bonus" in part.lower() for p in ctx.files() for part in p.parts):
        return True
    for p in ctx.files():
        if p.name == "Makefile" and re.search(r"^bonus\s*:", ctx.read(p), re.M):
            return True
    return False


def run_checks(ctx: Ctx, emit: Callable[[CheckResult], None]) -> None:
    from . import dynamic, static  # noqa: F401  (registers the checkers)

    for res in static.repo_hygiene(ctx):
        emit(res)

    bonus_submitted = _has_bonus(ctx)
    bonus_noted = False
    ordered = sorted(
        ctx.rules,
        key=lambda r: CHECKERS[r.kind][0] if r.kind in CHECKERS else PHASE_STATIC,
    )
    for rule in ordered:
        if rule.section == "bonus" and not bonus_submitted:
            if not bonus_noted:
                bonus_noted = True
                emit(CheckResult(
                    rule_id=None, title="Bonus part not submitted", status="skipped", section="bonus",
                    detail="No bonus files or `bonus` rule found, so the bonus requirements were not evaluated.",
                ))
            continue
        entry = CHECKERS.get(rule.kind)
        if entry is None:
            emit(result(rule, "manual", rule.text, auto=False))
            continue
        try:
            for res in entry[1](ctx, rule):
                emit(res)
        except SandboxError as exc:
            emit(result(rule, "skipped", f"Needs the sandbox: {exc}", title=label(rule)))
        except Exception as exc:  # a bug in one check must not abort the review
            emit(result(rule, "warn", f"The check itself crashed: {type(exc).__name__}: {exc}", title=label(rule)))

    if ctx.sandbox is not None:
        for res in dynamic.makefile_behavior(ctx):
            emit(res)
