"""The check engine: runs every rule of a session against a cloned repository."""

from __future__ import annotations

import re
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..models import CheckResult, Evidence, Rule, Section
from ..repo import empty_submodules, submodule_paths, tracked_files
from ..sandbox import ExecResult, Sandbox, SandboxError
from ..shared import strict_layout

VERDICT_MARKER = "<!-- generated by verdict -->"
GENERATED_VERDICT_NAMES = ("verdict.md", "verdict-report.md", "claude-review.md", "claude-review-report.md")
SOURCE_EXTS = {".c", ".h", ".cpp", ".hpp", ".tpp", ".ipp", ".cc"}
EXEC_MAGIC = (b"\x7fELF", b"\xcf\xfa\xed\xfe", b"\xfe\xed\xfa\xcf")  # ELF; Mach-O (for local dev)
LIBRARY_SUFFIXES = {".a", ".so", ".dylib"}
NOT_RUNNABLE_SUFFIXES = {".o", *LIBRARY_SUFFIXES}
# What a build prints when it tried to download something (git submodule update, curl, wget, pip...) and could not.
NETWORK_ERROR = re.compile(r"Could not resolve host|Temporary failure in name resolution|Name or service not known|Network is unreachable|"
                           r"Failed to connect to|Connection (?:refused|timed out)|unable to access '?https?://|Could not read from remote repository", re.I)
EXCLUDED_DIRS = re.compile(r"(^|/)(mlx|minilibx[\w.-]*|mlx_linux|mlx42|libmlx[\w.-]*|\.git)/", re.I)
# The 42 header the Norm asks for: code that has it was written by a student, not vendored.
HEADER_42 = re.compile(rb"By: \S+.*<.*>.*\n.*\n?.*Created: ", re.I)


def minilibx_dirs(root: Path, files: Iterable[Path]) -> list[str]:
    """The folders (relative to `root`) that hold a copy of MiniLibX, whatever they are called: a folder with mlx.h next to other
    mlx_* files (the classic MiniLibX), or the root of MLX42 (include/MLX42/MLX42.h). MiniLibX is given to the students, so it is
    not their code: the Norm and the code checks leave it out. The project's own root is never one of them."""
    by_dir: dict[Path, set[str]] = {}
    found: set[str] = set()
    for rel in files:
        by_dir.setdefault(rel.parent, set()).add(rel.name)
        if rel.name == "MLX42.h" and rel.parent.name == "MLX42" and rel.parent.parent.name == "include":
            found.add(rel.parent.parent.parent.as_posix())
    for folder, names in by_dir.items():
        if "mlx.h" in names and any(n != "mlx.h" and n.startswith("mlx_") for n in names):
            found.add(folder.as_posix())
    return sorted(f for f in found if f not in ("", "."))


@dataclass
class BuildResult:
    ok: bool
    log: str
    ran: bool = True
    needs_network: bool = False   # it failed while trying to download something, and the sandbox has no network


@dataclass
class Ctx:
    repo: Path
    rules: list[Rule]
    sandbox: Sandbox | None
    lang: str | None = None
    cache: dict[str, Any] = field(default_factory=dict)

    # ---- repo helpers
    @property
    def strict_layout(self) -> bool:
        """libft, ft_printf and get_next_line: the files to turn in must be exactly as the subject says. Everywhere else the layout of
        the subject is not binding: the files must exist, wherever they sit (see shared.evaluation_rules)."""
        if "strict_layout" not in self.cache:
            self.cache["strict_layout"] = strict_layout(s.pdf for r in self.rules for s in r.sources)
        return self.cache["strict_layout"]

    def unit_dir(self, unit: str) -> Path:
        path = (self.repo / unit).resolve()
        if unit in (".", "") or path.is_dir() or self.strict_layout:
            return path
        return (self.repo / self.moved_unit(unit)).resolve()

    def moved_unit(self, unit: str) -> str:
        """Where the work of a program folder the subject names (philo_bonus/) is looked for when the project does not have that
        folder: a project may share its code between programs (DRY) instead of copying the subject's layout. Only for folders that
        hold a program; a missing exercise folder (C++ modules) is missing work. `unit` itself when there is nothing to move to."""
        moved = self.cache.setdefault("moved_units", {})
        if unit not in moved:
            moved[unit] = unit
            if not (self.repo / unit).is_dir() and any(r.kind == "program" and r.unit == unit for r in self.rules):
                others = [u for u in dict.fromkeys(r.unit for r in self.rules) if u not in (".", "", unit)
                          and (self.repo / u / "Makefile").is_file()]
                candidates = [u for u in others if unit.startswith(u)] + (["."] if (self.repo / "Makefile").is_file() else []) + others
                moved[unit] = candidates[0] if candidates else "."
        return moved[unit]

    def minilibx_dirs(self) -> list[str]:
        if "minilibx_dirs" not in self.cache:
            self.cache["minilibx_dirs"] = minilibx_dirs(self.repo, tracked_files(self.repo))
        return self.cache["minilibx_dirs"]

    def is_vendored(self, rel: Path | str) -> bool:
        """Code given to the students (MiniLibX, under any folder name) rather than written by them."""
        posix = rel.as_posix() if isinstance(rel, Path) else str(rel)
        return bool(EXCLUDED_DIRS.search("/" + posix)) or any(posix.startswith(d + "/") for d in self.minilibx_dirs())

    def student_submodule_files(self) -> list[Path]:
        """Files of the submodules the student wrote (their libft, ft_printf...): a submodule is a way to copy their own code into the
        project, so the Norm applies to it. A submodule counts as theirs when one of its C files has the 42 header; MiniLibX never does."""
        if "student_submodule_files" not in self.cache:
            out: list[Path] = []
            for module in self.submodule_paths():
                base = self.repo / module
                if not base.is_dir():
                    continue
                files = [Path(module) / p for p in tracked_files(base)]
                sources = [p for p in files if p.suffix.lower() in (".c", ".h") and not self.is_vendored(p)]
                if any(HEADER_42.search((self.repo / p).read_bytes()[:2000]) for p in sources[:200] if (self.repo / p).is_file()):
                    out += sources
            self.cache["student_submodule_files"] = out
        return self.cache["student_submodule_files"]

    def files(self) -> list[Path]:
        """The project's own files: not the generated verdict, and not what lives in its submodules (those are other repositories)."""
        if "files" not in self.cache:
            modules = tuple(m.rstrip("/") + "/" for m in self.submodule_paths())
            self.cache["files"] = [p for p in tracked_files(self.repo)
                                   if not self._is_generated_verdict(p) and not p.as_posix().startswith(modules)]
        return self.cache["files"]

    def submodule_paths(self) -> list[str]:
        if "submodule_paths" not in self.cache:
            self.cache["submodule_paths"] = submodule_paths(self.repo)
        return self.cache["submodule_paths"]

    def offline_reason(self, build: "BuildResult") -> str:
        """Why a failed build cannot be judged: it needed the network (the sandbox has none) or submodules that were never downloaded.
        An empty string when the failure is the project's own."""
        if not build.ran:
            return ""
        # An empty submodule only explains a failure that talks about it (its folder, or something inside it that is missing):
        # a build that fails for the project's own reasons must stay a failure.
        empty = [p for p in empty_submodules(self.repo) if p in build.log or Path(p).name in build.log]
        if not (build.needs_network or empty):
            return ""
        tried = [n for n in self.cache.get("submodule_notes", []) if not n.ok]
        parts = ["The build could not be checked here: "
                 + ("it tried to download something and the sandbox has no network on purpose." if build.needs_network
                    else f"the submodule(s) {', '.join(empty)} are not downloaded, so the code they provide is missing.")]
        if tried:
            parts.append("The app tried to download the submodules ahead of the build and could not: "
                         + "; ".join(f"{n.path or 'submodules'}: {n.message}" for n in tried[:4]) + ".")
        elif empty:
            parts.append("The submodules are empty in the copy that is built.")
        parts.append("Build it yourself with the network on (⌨ Claude or ⌨ Shell in the project folder: `git submodule update --init`, then `make`) to settle this.")
        return " ".join(parts)

    def _is_generated_verdict(self, rel: Path) -> bool:
        if len(rel.parts) != 1 or rel.name not in GENERATED_VERDICT_NAMES:
            return False
        try:
            return (self.repo / rel).open("rb").read(200).startswith(VERDICT_MARKER.encode())
        except OSError:
            return False

    def walk(self, base: Path) -> list[Path]:
        """Fresh listing of `base` (the cached `files()` goes stale once the repo is built)."""
        return tracked_files(base)

    def source_files(self, unit: str = ".", *, exclude_vendored: bool = True) -> list[Path]:
        """Source files (relative to the repo root) under `unit`."""
        prefix = "" if unit in (".", "") else unit.rstrip("/") + "/"
        out = []
        for p in self.files():
            s = p.as_posix()
            if p.suffix.lower() in SOURCE_EXTS and s.startswith(prefix):
                if exclude_vendored and self.is_vendored(s):
                    continue
                out.append(p)
        return out

    def read(self, rel: Path) -> str:
        try:
            return (self.repo / rel).read_bytes()[:1_000_000].decode("utf-8", errors="replace")
        except OSError:
            return ""

    def is_elf(self, path: Path) -> bool:
        try:
            with path.open("rb") as fh:
                return fh.read(4) in EXEC_MAGIC
        except OSError:
            return False

    def executables(self, unit: str) -> list[Path]:
        """Programs that can be run. Object files and shared libraries are ELF as well, so the magic number is not enough."""
        base = self.unit_dir(unit)
        if not base.is_dir():
            return []
        return sorted(p for p in self._built_files(base) if p.suffix not in NOT_RUNNABLE_SUFFIXES
                      and p.stat().st_mode & 0o111 and self.is_elf(p))

    def libraries(self, unit: str) -> list[Path]:
        base = self.unit_dir(unit)
        if not base.is_dir():
            return []
        return sorted(p for p in self._built_files(base) if p.suffix in LIBRARY_SUFFIXES)

    @staticmethod
    def _built_files(base: Path) -> list[Path]:
        return [p for p in base.iterdir() if p.is_file() and not p.is_symlink()]

    # ---- rules helpers
    def units(self) -> list[str]:
        """The folders that are built, once each (two units can share a folder when the project shares its code)."""
        seen: dict[str, None] = {}
        for r in self.rules:
            if r.kind in ("build_unit", "program") or (r.kind == "required_files" and r.unit != "."):
                seen.setdefault(r.unit)
        out: list[str] = []
        folders: set[Path] = set()
        for unit in seen:
            folder = self.unit_dir(unit)
            if folder not in folders:
                folders.add(folder)
                out.append(unit)
        return out or ["."]

    def programs(self, unit: str, section: Section | None = None) -> list[str]:
        return [
            r.params["program"] for r in self.rules
            if r.kind == "program" and r.unit == unit and (section is None or r.section == section)
        ]

    def has_makefile(self, unit: str) -> bool:
        return (self.unit_dir(unit) / "Makefile").is_file()

    # ---- sandbox helpers
    def run(self, argv: list[str], unit: str = ".", timeout: float = 60, stdin: str = "") -> ExecResult:
        if self.sandbox is None:
            raise SandboxError("no sandbox configured")
        return self.sandbox.exec(argv, self.unit_dir(unit), timeout=timeout, stdin=stdin)

    def build(self, unit: str, bonus: bool = False) -> BuildResult:
        key = f"build:{unit}:{bonus}"
        if key not in self.cache:
            if not self.has_makefile(unit):
                self.cache[key] = BuildResult(False, f"No Makefile in {unit}/", ran=False)
            else:
                res = self.run(["make", "bonus"] if bonus else ["make"], unit, timeout=240)
                log = res.output + ("\n[timed out]" if res.timed_out else "")
                self.cache[key] = BuildResult(res.ok, log, needs_network=not res.ok and bool(NETWORK_ERROR.search(res.output)))
        return self.cache[key]


Checker = Callable[[Ctx, Rule], Iterable[CheckResult]]
CHECKERS: dict[str, tuple[int, Checker]] = {}

PHASE_STATIC, PHASE_BUILD, PHASE_ANALYSIS, PHASE_RUNTIME = range(4)


def checker(kind: str, phase: int) -> Callable[[Checker], Checker]:
    def register(fn: Checker) -> Checker:
        CHECKERS[kind] = (phase, fn)
        return fn
    return register


def result(rule: Rule | None, status: str, detail: str = "", *, title: str | None = None,
           evidence: list[Evidence] | None = None, log: str = "", auto: bool = True) -> CheckResult:
    return CheckResult(
        rule_id=rule.id if rule else None,
        title=title or (rule.title if rule else "Check"),
        status=status,  # type: ignore[arg-type]
        detail=detail,
        section=rule.section if rule else "mandatory",
        sources=rule.sources if rule else [],
        evidence=evidence or [],
        log=log[-6000:],
        auto=auto,
    )


def strip_code(text: str) -> str:
    """Blank out comments and string/char literals (keeping line numbers intact)."""
    out: list[str] = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        two = text[i:i + 2]
        if two == "//":
            j = text.find("\n", i)
            j = n if j == -1 else j
            out.append(" " * (j - i))
            i = j
        elif two == "/*":
            j = text.find("*/", i + 2)
            j = n if j == -1 else j + 2
            out.append(re.sub(r"[^\n]", " ", text[i:j]))
            i = j
        elif c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            end = min(j, n)
            closed = end < n and text[end] == c
            out.append(c + re.sub(r"[^\n]", " ", text[i + 1:end]) + (c if closed else ""))
            i = end + (1 if closed else 0)
        else:
            out.append(c)
            i += 1
    return "".join(out)


def grep(ctx: Ctx, files: Iterable[Path], pattern: re.Pattern[str], *, code_only: bool = True,
         limit: int = 25) -> list[Evidence]:
    found: list[Evidence] = []
    for rel in files:
        raw = ctx.read(rel)
        text = strip_code(raw) if code_only else raw
        raw_lines = raw.splitlines()
        for number, line in enumerate(text.splitlines(), 1):
            if pattern.search(line):
                snippet = raw_lines[number - 1].strip()[:200] if number <= len(raw_lines) else ""
                found.append(Evidence(file=rel.as_posix(), line=number, snippet=snippet))
                if len(found) >= limit:
                    return found
    return found


def label(rule: Rule, text: str | None = None) -> str:
    base = text or rule.title
    return base if rule.unit == "." else f"{rule.unit}: {base}"


def _has_bonus(ctx: Ctx) -> bool:
    """Whether the repo contains bonus work (bonus files/directories or a `bonus` Makefile rule)."""
    if any("bonus" in part.lower() for p in ctx.files() for part in p.parts):
        return True
    for p in ctx.files():
        if p.name == "Makefile" and re.search(r"^bonus\s*:", ctx.read(p), re.M):
            return True
    return False


def run_checks(ctx: Ctx, emit: Callable[[CheckResult], None]) -> None:
    from . import dynamic, static  # noqa: F401  (registers the checkers)

    for res in static.repo_hygiene(ctx):
        emit(res)
    for res in static.extras_check(ctx):
        emit(res)

    bonus_submitted = _has_bonus(ctx)
    bonus_noted = False
    ordered = sorted(
        ctx.rules,
        key=lambda r: CHECKERS[r.kind][0] if r.kind in CHECKERS else PHASE_STATIC,
    )
    for rule in ordered:
        if rule.section == "bonus" and not bonus_submitted:
            if not bonus_noted:
                bonus_noted = True
                emit(CheckResult(
                    rule_id=None, title="Bonus part not submitted", status="skipped", section="bonus",
                    detail="No bonus files or `bonus` rule found, so the bonus requirements were not evaluated.",
                ))
            continue
        entry = CHECKERS.get(rule.kind)
        if entry is None:
            emit(result(rule, "manual", rule.text, auto=False))
            continue
        try:
            for res in entry[1](ctx, rule):
                emit(res)
        except SandboxError as exc:
            emit(result(rule, "skipped", f"Needs the sandbox: {exc}", title=label(rule)))
        except Exception as exc:  # a bug in one check must not abort the review
            emit(result(rule, "warn", f"The check itself crashed: {type(exc).__name__}: {exc}", title=label(rule)))

    if ctx.sandbox is not None:
        for res in dynamic.makefile_behavior(ctx):
            emit(res)
